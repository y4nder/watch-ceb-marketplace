#!/usr/bin/env python3
"""Save a transcript + executive summary into a git-versioned transcripts repo.

Usage:
  save_transcript.py --transcript T.txt --summary S.md --title "DSM" [--type dsm]
                     [--date YYYY-MM-DD] [--tags a,b] [--participants a,b]
                     [--source PATH_OR_URL] [--no-push] [--dir DIR]
  save_transcript.py --reindex [--dir DIR]

Writes <dir>/<YYYY>/<date>-<slug>.md with YAML frontmatter, rebuilds INDEX.md,
commits, and pushes. Before pushing it makes sure the active gh account is
TRANSCRIPTS_GH_USER (if set). Pure stdlib.

Config (env vars or ~/.config/watch/.env):
  TRANSCRIPTS_DIR      default ~/transcripts
  TRANSCRIPTS_GH_USER  gh account that must be active before pushing
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import subprocess
import sys
from pathlib import Path

TYPES = ["dsm", "meeting", "consolidation", "demo", "recording", "other"]


def config(name: str, default: str = "") -> str:
    val = os.environ.get(name, "").strip()
    if val:
        return val
    env = Path.home() / ".config" / "watch" / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith(f"{name}="):
                return line.split("=", 1)[1].strip().strip("'\"")
    return default


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:60].rstrip("-") or "transcript"


def yaml_list(items: list[str]) -> str:
    return "[" + ", ".join(items) + "]"


def split_csv(s: str | None) -> list[str]:
    return [x.strip() for x in (s or "").split(",") if x.strip()]


def parse_frontmatter(text: str) -> dict:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end < 0:
        return {}
    meta = {}
    for line in text[4:end].splitlines():
        if ":" not in line:
            continue
        k, v = line.split(":", 1)
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            meta[k.strip()] = split_csv(v[1:-1])
        else:
            meta[k.strip()] = v.strip("'\"")
    return meta


def git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], check=check, text=True,
                          capture_output=True)


def reindex(repo: Path) -> None:
    rows = []
    for f in sorted(repo.glob("[0-9][0-9][0-9][0-9]/*.md")):
        m = parse_frontmatter(f.read_text(encoding="utf-8"))
        rows.append((m.get("date", ""), m.get("type", ""), m.get("title", f.stem),
                     ", ".join(m.get("tags", [])), f.relative_to(repo).as_posix()))
    rows.sort(key=lambda r: (r[0], r[4]), reverse=True)
    lines = [
        "# Transcripts index",
        "",
        "Generated by `save_transcript.py --reindex`; do not edit by hand.",
        "Search: `grep -l 'tags:.*dsm' 20*/*.md`, or `grep -ril <word> 20*/`.",
        "",
        "| Date | Type | Title | Tags |",
        "| --- | --- | --- | --- |",
    ]
    for date, typ, title, tags, path in rows:
        title = title.replace("|", "\\|")
        lines.append(f"| {date} | {typ} | [{title}]({path}) | {tags} |")
    (repo / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def ensure_gh_user(user: str) -> None:
    if not user:
        return
    cur = subprocess.run(["gh", "api", "user", "--jq", ".login"], text=True,
                         capture_output=True)
    # Last line only: shims like mise can print noise to stdout first.
    login = (cur.stdout.strip().splitlines() or [""])[-1].strip()
    if cur.returncode == 0 and login == user:
        return
    sw = subprocess.run(["gh", "auth", "switch", "-u", user], text=True, capture_output=True)
    if sw.returncode != 0:
        sys.exit(f"Could not switch gh to {user}: {sw.stderr.strip()} (run `gh auth login`)")
    print(f"# Switched active gh account to {user}", file=sys.stderr)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=config("TRANSCRIPTS_DIR", str(Path.home() / "transcripts")))
    ap.add_argument("--reindex", action="store_true")
    ap.add_argument("--transcript")
    ap.add_argument("--summary")
    ap.add_argument("--title")
    ap.add_argument("--type", default="other", choices=TYPES)
    ap.add_argument("--date", default=dt.date.today().isoformat())
    ap.add_argument("--tags")
    ap.add_argument("--participants")
    ap.add_argument("--source", default="")
    ap.add_argument("--transcriber", default="gemini")
    ap.add_argument("--no-push", action="store_true")
    a = ap.parse_args()

    repo = Path(os.path.expanduser(a.dir))
    if not (repo / ".git").exists():
        sys.exit(f"{repo} is not a git repo; set it up first (see the skill's 'Saving' section)")

    if a.reindex:
        reindex(repo)
        print(repo / "INDEX.md")
        return
    if not (a.transcript and a.summary and a.title):
        ap.error("--transcript, --summary and --title are required")
    dt.date.fromisoformat(a.date)  # validate

    transcript = Path(a.transcript).read_text(encoding="utf-8").strip()
    # Drop the script's own "# Transcript source" header line; it goes into frontmatter.
    transcript = re.sub(r"^# Transcript source:.*\n", "", transcript)
    summary = Path(a.summary).read_text(encoding="utf-8").strip()

    year_dir = repo / a.date[:4]
    year_dir.mkdir(exist_ok=True)
    base = f"{a.date}-{slugify(a.title)}"
    out, n = year_dir / f"{base}.md", 2
    while out.exists():
        out, n = year_dir / f"{base}-{n}.md", n + 1

    tags = split_csv(a.tags)
    if a.type not in tags:
        tags.insert(0, a.type)
    title = a.title.replace('"', "'")
    source = a.source.replace('"', "'")
    out.write_text(
        "---\n"
        f'title: "{title}"\n'
        f"date: {a.date}\n"
        f"type: {a.type}\n"
        f"tags: {yaml_list(tags)}\n"
        f"participants: {yaml_list(split_csv(a.participants))}\n"
        f'source: "{source}"\n'
        f"transcriber: {a.transcriber}\n"
        f"saved: {dt.datetime.now().isoformat(timespec='seconds')}\n"
        "---\n\n"
        f"# {a.title}\n\n"
        "## Executive summary\n\n"
        f"{summary}\n\n"
        "## Transcript\n\n"
        f"{transcript}\n",
        encoding="utf-8",
    )
    reindex(repo)

    rel = out.relative_to(repo).as_posix()
    git(repo, "add", rel, "INDEX.md")
    git(repo, "commit", "-m", f"Add transcript: {a.date} {a.title}")
    print(f"# Saved {out}")

    if a.no_push:
        return
    if not git(repo, "remote", check=False).stdout.strip():
        print("# No remote configured; committed locally only", file=sys.stderr)
        return
    ensure_gh_user(config("TRANSCRIPTS_GH_USER"))
    push = git(repo, "push", check=False)
    if push.returncode != 0:
        sys.exit(f"Committed locally, but push failed: {push.stderr.strip()}")
    print("# Pushed")


if __name__ == "__main__":
    main()
